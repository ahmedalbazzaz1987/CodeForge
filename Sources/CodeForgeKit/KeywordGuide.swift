    /// What a keyword means in a language, or nil when it isn't in the guide.
    public static func explain(_ word: String, languageId: String) -> String? {
        let family: String = switch languageId {
        case "typescript", "javascriptreact", "typescriptreact": "javascript"
        case "scss", "less": "css"
        case "objc": "c"
        default: languageId
        }
        func same(_ a: String) -> Bool { family == "vb" ? a.lowercased() == word.lowercased() : a == word }
        func applies(_ languages: String) -> Bool {
            let list = languages.split(separator: " ").map(String.init)
            return list.contains(family) || (family == "cpp" && list.contains("c"))
        }
        if let match = entries.first(where: { !$0.languages.isEmpty && applies($0.languages) && same($0.word) }) { return match.meaning }
        // CSS properties mean nothing as words of other languages.
        if family == "css" { return nil }
        return entries.first { $0.languages.isEmpty && same($0.word) }?.meaning
    }
